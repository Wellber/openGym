export function tr(key, ...args) {
  const lang = getLang() || ''
  const s = (lang === 'pt' || lang.startsWith('pt-')) ? (PT[key] || key) : key
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (args[i] != null ? String(args[i]) : m)) : s
}
